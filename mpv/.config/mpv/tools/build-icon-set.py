#!/usr/bin/env python3
# Builds an alternative icon set for uosc from a codepoint icon font, such as Lucide's
# (https://lucide.dev, the lucide-static package: font/lucide.ttf and font/info.json).
#
# icon-sets/<set>.txt maps uosc's icon names, which are Material Symbols names, to the set's
# own names, and `@scale` sizes its icons relative to Material's. The script cuts the font
# down to those glyphs, renames its family so it never clashes with a system copy, and
# writes a Lua table uosc loads when `icon_set=<set>`:
#   fonts/<set>-mpv.ttf
#   scripts/uosc/lib/icon-sets/<set>.lua
# Icons missing from the map are drawn from the Material font as before.
#
# Usage: build-icon-set.py lucide lucide.ttf info.json
# Needs fonttools.

import json
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def read_map(path):
	"""Returns the name pairs and the `@scale` directive (1 when absent)."""
	pairs, scale = [], 1.0
	with open(path) as f:
		for line in f:
			fields = line.split('#', 1)[0].split()
			if len(fields) == 2 and fields[0] == '@scale':
				scale = float(fields[1])
			elif len(fields) == 2:
				pairs.append(fields)
	return pairs, scale


def codepoint(entry):
	# info.json stores codepoints as CSS escapes, e.g. "\\e140"
	return int(entry['encodedCode'].lstrip('\\'), 16)


def fix_metrics(font):
	"""Makes libass centre each icon in its em square.

	Lucide's font records a left side bearing of 0 for every glyph although the outlines
	start further in; FreeType trusts the recorded value and shifts each icon left by the
	difference. Its Windows ascent and descent (1090/6) also disagree with the em box
	(1000/0) that the outlines are centred in, which drops icons slightly.
	"""
	glyf, hmtx = font['glyf'], font['hmtx']
	for name in font.getGlyphOrder():
		glyph = glyf[name]
		glyph.recalcBounds(glyf)
		advance, _ = hmtx[name]
		hmtx[name] = (advance, getattr(glyph, 'xMin', 0) if glyph.numberOfContours else 0)

	em = font['head'].unitsPerEm
	hhea, os2 = font['hhea'], font['OS/2']
	hhea.ascent, hhea.descent, hhea.lineGap = em, 0, 0
	os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap = em, 0, 0
	os2.usWinAscent, os2.usWinDescent = em, 0


def main(name, font_path, info_path):
	family = f'{name}-mpv'
	pairs, scale = read_map(os.path.join(HERE, 'icon-sets', f'{name}.txt'))
	info = json.load(open(info_path))

	missing = sorted({icon for _, icon in pairs if icon not in info})
	if missing:
		sys.exit(f'not in {name}: ' + ', '.join(missing))

	glyphs = {uosc: codepoint(info[icon]) for uosc, icon in pairs}

	font = TTFont(font_path)
	cmap = font.getBestCmap()
	absent = sorted(uosc for uosc, cp in glyphs.items() if cp not in cmap)
	if absent:
		sys.exit('codepoints not in the font for: ' + ', '.join(absent))

	options = subset.Options()
	options.glyph_names = True
	options.name_IDs = list(range(26))
	options.layout_features = []
	subsetter = subset.Subsetter(options)
	subsetter.populate(unicodes=sorted(set(glyphs.values())))
	subsetter.subset(font)
	fix_metrics(font)
	for record in font['name'].names:
		if record.nameID in (1, 3, 4, 6, 16):
			record.string = family
	font_out = os.path.join(ROOT, 'fonts', f'{family}.ttf')
	font.save(font_out)

	lua_out = os.path.join(ROOT, 'scripts', 'uosc', 'lib', 'icon-sets', f'{name}.lua')
	os.makedirs(os.path.dirname(lua_out), exist_ok=True)
	with open(lua_out, 'w') as f:
		f.write(f'-- Generated by tools/build-icon-set.py from tools/icon-sets/{name}.txt; do not edit.\n')
		f.write(f'return {{\n\tfont = {json.dumps(family)},\n\tscale = {scale},\n\tglyphs = {{\n')
		for uosc in sorted(glyphs):
			utf8 = ''.join(f'\\{b}' for b in chr(glyphs[uosc]).encode('utf-8'))
			f.write(f'\t\t["{uosc}"] = "{utf8}",\n')
		f.write('\t},\n}\n')

	print(f'{font_out}: {len(set(glyphs.values()))} glyphs\n{lua_out}: {len(glyphs)} names')


if __name__ == '__main__':
	main(*sys.argv[1:4])
